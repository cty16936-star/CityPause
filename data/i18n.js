Object.entries(I18N_EXTRA).forEach(([code, strings]) => {
  Object.assign(window.I18N[code], strings);
});

const LANGUAGE_KEY = "city_mirror_lang";
const languageCodes = new Set(window.I18N_LANGS.map(({ code }) => code));
let activeLanguage = (() => {
  const saved = localStorage.getItem(LANGUAGE_KEY);
  if (languageCodes.has(saved)) return saved;
  const browserLanguage = (navigator.language || "en").slice(0, 2).toLowerCase();
  return languageCodes.has(browserLanguage) ? browserLanguage : "en";
})();

window.t = (key, values = {}) => {
  const catalog = window.I18N[activeLanguage] || window.I18N.zh;
  const template = catalog[key] ?? window.I18N.zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : match
  );
};

window.applyTranslations = () => {
  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = window.t(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.setAttribute("placeholder", window.t(element.dataset.i18nPlaceholder));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
    element.setAttribute("aria-label", window.t(element.dataset.i18nAriaLabel));
  });
};

function renderLanguageMenu() {
  const menu = document.getElementById("lang-menu");
  const current = document.getElementById("lang-current");
  const active = window.I18N_LANGS.find(({ code }) => code === activeLanguage);
  current.textContent = active.native;
  menu.replaceChildren();
  window.I18N_LANGS.forEach(language => {
    const option = document.createElement("button");
    option.type = "button";
    option.className = "lang-option";
    if (language.code === activeLanguage) option.classList.add("active");
    option.append(document.createTextNode(language.native));
    const name = document.createElement("small");
    name.textContent = language.name;
    option.appendChild(name);
    option.lang = language.code;
    option.setAttribute("aria-pressed", String(language.code === activeLanguage));
    option.addEventListener("click", () => window.setLanguage(language.code));
    menu.appendChild(option);
  });
  document.getElementById("lang-toggle").setAttribute(
    "aria-label",
    `${window.t("language_label")}: ${active.native}`
  );
}

window.setLanguage = code => {
  if (!languageCodes.has(code)) {
    throw new RangeError(`Unsupported language: ${code}`);
  }
  activeLanguage = code;
  localStorage.setItem(LANGUAGE_KEY, code);
  document.documentElement.lang = code;
  document.documentElement.dir = window.I18N_LANGS.find(language => language.code === code).dir;
  window.applyTranslations();
  renderLanguageMenu();
  languageMenu.classList.remove("open");
  languageToggle.setAttribute("aria-expanded", "false");
  window.dispatchEvent(new CustomEvent("languagechange", { detail: { language: code } }));
};

const languageToggle = document.getElementById("lang-toggle");
const languageMenu = document.getElementById("lang-menu");
languageToggle.addEventListener("click", () => {
  const isOpen = languageMenu.classList.toggle("open");
  languageToggle.setAttribute("aria-expanded", String(isOpen));
});
document.addEventListener("click", event => {
  if (!event.target.closest("#lang-picker")) {
    languageMenu.classList.remove("open");
    languageToggle.setAttribute("aria-expanded", "false");
  }
});
document.addEventListener("keydown", event => {
  if (event.key === "Escape") {
    languageMenu.classList.remove("open");
    languageToggle.setAttribute("aria-expanded", "false");
  }
});

document.documentElement.lang = activeLanguage;
document.documentElement.dir = window.I18N_LANGS.find(language => language.code === activeLanguage).dir;
window.applyTranslations();
renderLanguageMenu();